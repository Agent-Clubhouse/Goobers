// Command generate pins the stable app-server schemas to a local Codex CLI.
// The regeneration/check workflow follows Clubhouse (MIT), commit 3309665c,
// scripts/generate-codex-app-server-types.mjs. See ../CLUBHOUSE-LICENSE.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

const version = "0.163.0"

var roots = []string{
	"v1/InitializeParams", "v1/InitializeResponse",
	"v2/ThreadStartParams", "v2/ThreadStartResponse", "v2/ThreadResumeParams",
	"v2/TurnStartParams", "v2/TurnStartResponse", "v2/TurnSteerParams", "v2/TurnSteerResponse",
	"v2/TurnInterruptParams", "v2/ModelListParams", "v2/ModelListResponse",
	"v2/TurnStartedNotification", "v2/TurnCompletedNotification",
	"v2/ItemStartedNotification", "v2/ItemCompletedNotification",
	"v2/AgentMessageDeltaNotification", "v2/ThreadTokenUsageUpdatedNotification",
	"v2/ErrorNotification", "CommandExecutionRequestApprovalParams",
	"FileChangeRequestApprovalParams", "ToolRequestUserInputParams",
}

type schema map[string]any

func main() {
	check := flag.Bool("check", false, "fail if pinned generated bindings drift")
	binary := flag.String("codex", "codex", "installed CLI (must match pinned version)")
	out := flag.String("out", "internal/codexprotocol/generated.go", "generated Go file")
	flag.Parse()
	if err := generate(*binary, *out, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(binary, out string, check bool) error {
	v, err := exec.Command(binary, "--version").Output()
	if err != nil {
		return fmt.Errorf("probe codex version: %w", err)
	}
	if strings.TrimSpace(string(v)) != "codex-cli "+version {
		return fmt.Errorf("schema generation requires codex-cli %s", version)
	}
	dir, err := os.MkdirTemp("", "goobers-codex-schema-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(dir)
	if result, err := exec.Command(binary, "app-server", "generate-json-schema", "--out", dir).CombinedOutput(); err != nil {
		return fmt.Errorf("generate schemas: %w: %s", err, result)
	}
	g := &generator{types: map[string]schema{}}
	hash := sha256.New()
	for _, name := range append(append([]string{}, roots...), "ServerNotification", "ServerRequest") {
		data, err := os.ReadFile(filepath.Join(dir, name+".json"))
		if err != nil {
			return err
		}
		var s schema
		if err := json.Unmarshal(data, &s); err != nil {
			return err
		}
		canonical, _ := json.Marshal(s)
		fmt.Fprintf(hash, "%s\n%s\n", name, canonical)
		if name == "ServerNotification" || name == "ServerRequest" {
			g.methods = append(g.methods, methodList(name, s))
			continue
		}
		g.types[filepath.Base(name)] = s
		for n, d := range object(s["definitions"]) {
			next := schema(object(d))
			if old, ok := g.types[n]; ok {
				a, _ := json.Marshal(old)
				b, _ := json.Marshal(next)
				if !bytes.Equal(a, b) {
					return fmt.Errorf("conflicting schema definition %s", n)
				}
			}
			g.types[n] = next
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by go run ./internal/codexprotocol/generate; DO NOT EDIT.\npackage codexprotocol\n\nimport \"encoding/json\"\n\nconst Version = %q\nconst SchemaSHA256 = %q\n\n", version, fmt.Sprintf("%x", hash.Sum(nil)))
	names := make([]string, 0, len(g.types))
	for name := range g.types {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		kind := g.typ(g.types[name])
		if kind == "json.RawMessage" {
			kind = "= " + kind
		}
		fmt.Fprintf(&b, "type %s %s\n\n", goName(name), kind)
	}
	for _, list := range g.methods {
		b.WriteString(list)
	}
	data, err := format.Source([]byte(b.String()))
	if err != nil {
		return err
	}
	if check {
		old, err := os.ReadFile(out)
		if err != nil || !bytes.Equal(old, data) {
			return fmt.Errorf("Codex %s schema drift: run go run ./internal/codexprotocol/generate", version)
		}
		return nil
	}
	return os.WriteFile(out, data, 0o644)
}

type generator struct {
	types   map[string]schema
	methods []string
}

func object(v any) map[string]any {
	m, _ := v.(map[string]any)
	return m
}

func goName(name string) string {
	parts := strings.FieldsFunc(name, func(r rune) bool { return r == '_' || r == '-' })
	for i, p := range parts {
		parts[i] = strings.ToUpper(p[:1]) + p[1:]
	}
	return strings.Join(parts, "")
}

// Unions retain their wire representation. Optional nullable scalar fields use
// pointers: nil omits an override, while an explicit zero remains representable.
func (g *generator) typ(s schema) string {
	if ref, ok := s["$ref"].(string); ok {
		return goName(strings.TrimPrefix(ref, "#/definitions/"))
	}
	for _, key := range []string{"anyOf", "oneOf", "allOf"} {
		if alternatives, ok := s[key].([]any); ok {
			var nonnull []schema
			nullable := false
			for _, a := range alternatives {
				item := schema(object(a))
				if item["type"] == "null" {
					nullable = true
				} else {
					nonnull = append(nonnull, item)
				}
			}
			if len(nonnull) == 1 {
				t := g.typ(nonnull[0])
				if nullable && t != "json.RawMessage" {
					return "*" + t
				}
				return t
			}
			return "json.RawMessage"
		}
	}
	if types, ok := s["type"].([]any); ok {
		for _, t := range types {
			if t != "null" {
				c := schema{}
				for k, v := range s {
					c[k] = v
				}
				c["type"] = t
				return "*" + g.typ(c)
			}
		}
	}
	switch s["type"] {
	case "string":
		return "string"
	case "integer":
		return "int64"
	case "number":
		return "float64"
	case "boolean":
		return "bool"
	case "array":
		return "[]" + g.typ(schema(object(s["items"])))
	case "object":
		return g.structType(s)
	default:
		return "json.RawMessage"
	}
}

func (g *generator) structType(s schema) string {
	properties := object(s["properties"])
	if len(properties) == 0 {
		return "map[string]json.RawMessage"
	}
	required := map[string]bool{}
	if fields, ok := s["required"].([]any); ok {
		for _, f := range fields {
			required[f.(string)] = true
		}
	}
	names := make([]string, 0, len(properties))
	for name := range properties {
		names = append(names, name)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("struct {\n")
	for _, name := range names {
		tag := name
		if !required[name] {
			tag += ",omitempty"
		}
		fmt.Fprintf(&b, "%s %s `json:%q`\n", goName(name), g.typ(schema(object(properties[name]))), tag)
	}
	b.WriteString("}")
	return b.String()
}

func methodList(name string, s schema) string {
	var methods []string
	for _, v := range s["oneOf"].([]any) {
		p := object(object(v)["properties"])
		if enums, ok := object(p["method"])["enum"].([]any); ok {
			for _, method := range enums {
				methods = append(methods, method.(string))
			}
		}
	}
	sort.Strings(methods)
	var b strings.Builder
	fmt.Fprintf(&b, "var %sMethods = map[string]bool{\n", name)
	for _, method := range methods {
		fmt.Fprintf(&b, "%q: true,\n", method)
	}
	b.WriteString("}\n")
	return b.String()
}
